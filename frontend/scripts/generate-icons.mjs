const require = createRequire(import.meta.url);
const iconsDir = path.join(path.dirname(require.resolve("bootstrap-icons/package.json")), "icons");

const entries = ICONS.sort().map((name) => {
  const svg = readFileSync(path.join(iconsDir, `${name}.svg`), "utf8");
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s+/g, " ")
    .trim();
  return `  "${name}": ${JSON.stringify(inner)},`;
});

const out = `// Generated by scripts/generate-icons.mjs. Do not edit by hand.
// Source: Bootstrap Icons (MIT License).
export const ICONS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof ICONS;
`;

writeFileSync(new URL("../src/components/ui/icons.generated.ts", import.meta.url), out);
console.log(`Generated ${entries.length} icons.`);
